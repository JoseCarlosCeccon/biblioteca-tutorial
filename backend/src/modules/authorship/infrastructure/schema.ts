import { sql } from "../../../infrastructure/postgres";

// O id vai explícito de propósito: é ele que faz o ON CONFLICT ser
// idempotente, e é ele que os exemplos deste documento referenciam.
export const INITIAL_AUTHORS = [
  [1, "Eric Evans", "didatico"],
  [2, "Robert C. Martin", "didatico"],
  [3, "Harper Lee", "literatura"],
  [4, "Jane Austen", "literatura"],
] as const;

/** O módulo Autoria é o dono da tabela `autores` — e da carga inicial dela. */
export async function prepareAuthorship(): Promise<void> {
  await sql`
    CREATE TABLE IF NOT EXISTS autores (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nome TEXT NOT NULL,
      orcid TEXT UNIQUE,
      tipo TEXT NOT NULL DEFAULT 'literatura',
      livros_no_acervo INTEGER NOT NULL DEFAULT 0
    )
  `;

  await sql`CREATE TABLE IF NOT EXISTS autoria_migracoes (nome TEXT PRIMARY KEY)`;
  await sql.begin(async (tx) => {
    await tx`SELECT pg_advisory_xact_lock(22001)`;
    const [applied] = await tx`SELECT nome FROM autoria_migracoes WHERE nome = 'carga-inicial'`;
    if (applied) return;
    for (const [id, name, type] of INITIAL_AUTHORS) {
      await tx`
        INSERT INTO autores (id, nome, tipo) VALUES (${id}, ${name}, ${type})
        ON CONFLICT (id) DO NOTHING
      `;
    }
    // Executa uma vez: reiniciar o servidor não ressuscita autores excluídos.
    await tx`SELECT setval(pg_get_serial_sequence('autores', 'id'), (SELECT MAX(id) FROM autores))`;
    await tx`INSERT INTO autoria_migracoes (nome) VALUES ('carga-inicial')`;
  });
}
